-- Schema inicial: as seis entidades do modelo (ver AGENTS.md §3)

-- Consultor: usuário que faz login e atende clientes
CREATE TABLE consultores (
    id_consultor INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome         VARCHAR(255)  NOT NULL,
    email        VARCHAR(255)  NOT NULL UNIQUE,
    senha_hash   VARCHAR(255)  NOT NULL,
    area         VARCHAR(255),
    meta         NUMERIC(15, 2)
);

-- Cliente: empresa da carteira, atendida por um consultor
CREATE TABLE clientes (
    id_cliente    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_consultor  INTEGER        NOT NULL REFERENCES consultores (id_consultor),
    nome          VARCHAR(255)   NOT NULL,
    segmento      VARCHAR(255),
    nivel         CHAR(1)        CHECK (nivel IN ('A', 'B', 'C')),
    faturamento   NUMERIC(15, 2),
    data_cadastro DATE
);

-- Serviço: produto que pode ser contratado
CREATE TABLE servicos (
    id_servico INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome       VARCHAR(255) NOT NULL,
    descricao  VARCHAR(255),
    categoria  VARCHAR(255)
);

-- Contrato: liga cliente a serviço (data_fim nula = vigente)
CREATE TABLE contratos (
    id_contrato INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_cliente  INTEGER        NOT NULL REFERENCES clientes (id_cliente),
    id_servico  INTEGER        NOT NULL REFERENCES servicos (id_servico),
    data_inicio DATE           NOT NULL,
    data_fim    DATE,
    valor       NUMERIC(15, 2),
    status      VARCHAR(255)
);

-- Insight: análise gerada; cliente e contrato são opcionais (insights da carteira toda)
CREATE TABLE insights (
    id_insight   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_cliente   INTEGER REFERENCES clientes (id_cliente),
    id_contrato  INTEGER REFERENCES contratos (id_contrato),
    tipo         VARCHAR(255)  NOT NULL,
    descricao    VARCHAR(1000),
    tag          VARCHAR(255),
    valor        DOUBLE PRECISION,
    data_geracao TIMESTAMP
);

-- Telemetria: registro de cada upload de planilha, para auditoria
CREATE TABLE telemetrias (
    id_telemetria         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_consultor          INTEGER      NOT NULL REFERENCES consultores (id_consultor),
    data_upload           TIMESTAMP,
    nome_arquivo          VARCHAR(255) NOT NULL,
    registros_processados INTEGER,
    status                VARCHAR(255)
);
